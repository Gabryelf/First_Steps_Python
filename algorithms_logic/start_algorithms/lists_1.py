# Каждый список имеет три основные операции:
# 1. Создать список
# 2. Добавить в список
# 3. Прочитать из списка

products = ["молоко", "хлеб", "яйца", "сыр"]

# Чтение элементов
products[0]      # Первый элемент: "молоко"
products[-1]     # Последний элемент: "сыр"

# Изменение списка
products.append("масло")          # Добавить в конец
products.insert(1, "мед")         # Вставить на позицию
products.remove("хлеб")           # Удалить по значению

print(len(products))                   # Длина списка